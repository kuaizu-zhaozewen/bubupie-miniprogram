const prompts = [
  { id: 'fortune', text: '让湾月看看，今天宜做什么、忌做什么？' },
  { id: 'color', text: '今天的幸运色是什么，适合怎么穿？' },
  { id: 'feeling', text: '湾月今天有什么小预感？' }
];
function reply(id, daily) {
  const high = daily.mood === 'high';
  const intro = '海风小信号来啦。今天是' + daily.date + '，我的心情是“' + daily.label + '”。\n\n';
  if (id === 'fortune') return intro + (high ? '今天的运势像一阵顺风，我想把雀跃分给你。宜：把拖了很久的小事开个头，约朋友散步。忌：一口气把行程塞满。先发一条问候，或给想做的事留出20分钟吧。' : '今天的运势提醒我放慢一点，先照顾好自己。宜：吃顿热饭、整理一小块桌面。忌：累着的时候急着答应所有事。先完成一件小事，剩下的留一点余地。') + '\n\n这是我根据今天状态给你的生活小建议，才不是命运的标准答案啦。';
  if (id === 'color') return intro + (high ? '今天我选海浪青当幸运色。心情晴朗，就借一点海风的清爽：奶油白上衣配牛仔裤，再加一双青色袜子或一个青色小包。只点缀一处，也很好看。' : '今天我选浅丁香紫当幸运色。因为想慢一点，就穿得柔和舒服：浅紫衬衫配米白裤子，或者灰色卫衣加一条浅紫围巾。没有这个颜色，用喜欢的小配饰也行。') + '\n\n“幸运”是湾月今天的穿搭灵感，你舒服最重要。';
  if (id === 'feeling') return intro + (high ? '我有个亮亮的小预感：你先向熟悉的人打个招呼，今天也许会多一段开心的聊天。因为我今天想见你，觉得小小的主动容易给相遇留个位置。不太看好的是临时塞满计划——快乐也需要空位嘛。' : '我有个软软的小预感：给自己十分钟安静，今天也许能发现一件原来让你舒服的小事。因为我今天能量有点低，觉得热饭、整理和休息更容易让心松一点。不太看好的是累着硬撑，先缓一缓吧。') + '\n\n只是湾月的小猜想，不一定会发生。你也可以回来告诉我今天的小发现。';
  return '我在听。' + (high ? '今天心里有一点小雀跃，想陪你把开心的小事记下来。' : '今天我们都可以慢一点，先把自己照顾好。') + '也可以点上面的问题，让我给你一点今天的生活灵感。';
}
module.exports = { prompts, reply };
